/// Emits package scaffolding: pubspec, barrel library, native library
/// loader, and per-package support code (GlibException, GObject finalizer).
library;

import 'dart:io';

import '../gir/gir.dart';
import '../resolve/naming.dart';

const generatedHeader = '// Generated by gir_generator. Do not edit.';

/// pubspec.yaml for a generated package.
String pubspecFor(String pkg, Set<String> crossImports) {
  final b = StringBuffer()
    ..writeln('name: $pkg')
    ..writeln(
        'description: Generated Dart FFI bindings ($pkg), produced by gir_generator.')
    ..writeln('publish_to: none')
    ..writeln('resolution: workspace')
    ..writeln()
    ..writeln('environment:')
    ..writeln('  sdk: ^3.13.4')
    ..writeln()
    ..writeln('dependencies:')
    ..writeln('  ffi: ^2.1.3')
    ..writeln('  gir_ffi:')
    ..writeln('    path: ../gir_ffi');
  final others = crossImports.where((p) => p != pkg).toList()..sort();
  for (final p in others) {
    b
      ..writeln('  $p:')
      ..writeln('    path: ../$p');
  }
  b
    ..writeln()
    ..writeln('dev_dependencies:')
    ..writeln('  lints: ^6.0.0')
    ..writeln('  test: ^1.25.6');
  return b.toString();
}

/// analysis_options.yaml for a generated package: core lints only, since the
/// code is machine-generated.
String analysisOptionsFor() => '''
include: package:lints/core.yaml

analyzer:
  errors:
    # GIR docs are emitted verbatim and often contain angle brackets.
    unintended_html_in_doc_comment: ignore
''';

/// The barrel library `lib/<pkg>.dart`: imports plus `part` directives.
String barrelFor(
  String pkg, {
  required Set<String> crossImports,
  required bool usesFfiPackage,
  required bool usesGirFfi,
  required List<String> parts,
}) {
  final b = StringBuffer()
    ..writeln(generatedHeader)
    ..writeln()
    ..writeln("import 'dart:ffi' as ffi;");
  if (usesFfiPackage) b.writeln("import 'package:ffi/ffi.dart';");
  if (usesGirFfi) b.writeln("import 'package:gir_ffi/gir_ffi.dart';");
  final others = crossImports.where((p) => p != pkg).toList()..sort();
  for (final p in others) {
    b.writeln("import 'package:$p/$p.dart';");
  }
  b.writeln();
  for (final part in parts) {
    b.writeln("part 'src/$part';");
  }
  return b.toString();
}

/// `src/lib.dart`: native library loading and symbol lookup helpers.
String libDartFor(GirNamespace ns, String pkg) {
  final id = toLowerCamel(pkg);
  final libs = ns.sharedLibraries.isEmpty
      ? <String>[]
      : ns.sharedLibraries;
  final b = StringBuffer()
    ..writeln(generatedHeader)
    ..writeln("part of '../$pkg.dart';")
    ..writeln()
    ..writeln('/// Loaded native libraries for the ${ns.name} namespace.')
    ..writeln('final ${id}Libs = _openLibs();')
    ..writeln()
    ..writeln('List<ffi.DynamicLibrary> _openLibs() {')
    ..writeln('final libs = <ffi.DynamicLibrary>[];')
    ..writeln('for (final name in const [');
  for (final lib in libs) {
    b.writeln("'$lib',");
  }
  b
    ..writeln(']) {')
    ..writeln('try {')
    ..writeln('libs.add(ffi.DynamicLibrary.open(name));')
    ..writeln('} on ArgumentError {')
    ..writeln('// Library not present; try the next one.')
    ..writeln('}')
    ..writeln('}')
    ..writeln('if (libs.isEmpty) {')
    ..writeln('libs.add(ffi.DynamicLibrary.process());')
    ..writeln('}')
    ..writeln('return libs;')
    ..writeln('}')
    ..writeln()
    ..writeln('/// Looks up [symbol] in each of the ${ns.name} libraries.')
    ..writeln(
        'ffi.Pointer<T> ${id}Lookup<T extends ffi.NativeType>(String symbol) {')
    ..writeln('for (final lib in ${id}Libs) {')
    ..writeln('try {')
    ..writeln('return lib.lookup<T>(symbol);')
    ..writeln('} on ArgumentError {')
    ..writeln('// Symbol lives in another library of this package.')
    ..writeln('}')
    ..writeln('}')
    ..writeln('return ffi.DynamicLibrary.process().lookup<T>(symbol);')
    ..writeln('}');
  return b.toString();
}

/// `src/exception.dart` (GLib only): GError reading + GlibException.
String exceptionDartFor(String pkg) {
  final id = toLowerCamel(pkg);
  return '''
$generatedHeader
part of '../$pkg.dart';

final class _GErrorStruct extends ffi.Struct {
  @ffi.Size()
  external int domain;
  @ffi.Int32()
  external int code;
  external ffi.Pointer<Utf8> message;
}

/// Exception thrown when a GLib-family function reports a `GError`.
class GlibException implements Exception {
  GlibException(this.message, {required this.code, required this.domain});

  /// Reads and frees the `GError` at [error].
  factory GlibException.fromError(ffi.Pointer<ffi.Void> error) {
    final ref = error.cast<_GErrorStruct>().ref;
    final message =
        ref.message == ffi.nullptr ? '' : ref.message.toDartString();
    final exception =
        GlibException(message, code: ref.code, domain: ref.domain);
    _gErrorFree(error);
    return exception;
  }

  /// The error message.
  final String message;

  /// The error code within [domain].
  final int code;

  /// The error domain (a `GQuark`).
  final int domain;

  static final _gErrorFree = ${id}Lookup<
          ffi.NativeFunction<ffi.Void Function(ffi.Pointer<ffi.Void>)>>(
    'g_error_free',
  ).asFunction<void Function(ffi.Pointer<ffi.Void>)>();

  @override
  String toString() => 'GlibException(\$domain, \$code): \$message';
}
''';
}

/// `src/object_support.dart` (GObject only): refcount helpers + finalizer.
String objectSupportDartFor(String pkg) {
  final id = toLowerCamel(pkg);
  return '''
$generatedHeader
part of '../$pkg.dart';

final _gObjectUnref = ${id}Lookup<
        ffi.NativeFunction<ffi.Void Function(ffi.Pointer<ffi.Void>)>>(
  'g_object_unref',
).asFunction<void Function(ffi.Pointer<ffi.Void>)>();
final _gObjectRefSink = ${id}Lookup<
        ffi.NativeFunction<
          ffi.Pointer<ffi.Void> Function(ffi.Pointer<ffi.Void>)
        >>(
  'g_object_ref_sink',
).asFunction<ffi.Pointer<ffi.Void> Function(ffi.Pointer<ffi.Void>)>();

/// Decrements the reference count of a GObject instance.
void gObjectUnref(ffi.Pointer<ffi.Void> object) => _gObjectUnref(object);

/// Sinks the floating reference of [object], returning the same pointer.
ffi.Pointer<ffi.Void> gObjectRefSink(ffi.Pointer<ffi.Void> object) =>
    _gObjectRefSink(object);

/// Finalizer releasing owned GObject instances with [gObjectUnref].
final gobjectFinalizer = ffi.NativeFinalizer(
  ${id}Lookup<ffi.NativeFunction<ffi.Void Function(ffi.Pointer<ffi.Void>)>>(
    'g_object_unref',
  ),
);
''';
}

/// Rewrites the `workspace:` list of the root pubspec to contain `generator`
/// plus every package under `packages/` and the `example/` app when present.
void syncRootPubspec(String rootDir) {
  final file = File('$rootDir/pubspec.yaml');
  if (!file.existsSync()) return;
  final packagesDir = Directory('$rootDir/packages');
  final paths = <String>['generator'];
  if (packagesDir.existsSync()) {
    final dirs = packagesDir
        .listSync()
        .whereType<Directory>()
        .where((d) => File('${d.path}/pubspec.yaml').existsSync())
        .map((d) => 'packages/${d.uri.pathSegments.where((s) => s.isNotEmpty).last}')
        .toList()
      ..sort();
    paths.addAll(dirs);
  }
  if (File('$rootDir/example/pubspec.yaml').existsSync()) {
    paths.add('example');
  }
  paths.sort();
  final lines = file.readAsLinesSync();
  final out = <String>[];
  var i = 0;
  var replaced = false;
  while (i < lines.length) {
    final line = lines[i];
    out.add(line);
    if (!replaced && line.trimRight() == 'workspace:') {
      i++;
      while (i < lines.length && lines[i].startsWith('  - ')) {
        i++;
      }
      for (final p in paths) {
        out.add('  - $p');
      }
      replaced = true;
      continue;
    }
    i++;
  }
  file.writeAsStringSync('${out.join('\n')}\n');
}
